/*
# Storage Buckets and Policies

## Overview
Creates two Supabase Storage buckets:

1. **public-assets** (public) — stores plan images, testimonial photos, blog post images,
   team member photos, how-it-works step images. Anyone can read; only admins can upload/update/delete.

2. **paid-content** (private) — stores PDFs and videos for plans. These are NOT publicly accessible.
   Only admins can upload/manage files. Customers access them only via temporary signed URLs
   generated by the `get-paid-content` edge function after payment verification.

## Policies

### public-assets bucket
- SELECT (read): public — `TO anon, authenticated USING (true)`
- INSERT (upload): admin only — `WITH CHECK (is_admin())`
- UPDATE: admin only
- DELETE: admin only

### paid-content bucket
- SELECT: admin only (public users get signed URLs from the edge function, not direct access)
- INSERT: admin only
- UPDATE: admin only
- DELETE: admin only

## Important Notes
1. The `paid-content` bucket is private — no public read policy. Customers never get direct storage access.
2. Signed URLs are generated server-side by the edge function using the service role key, with a short
   expiry (e.g. 60 minutes). The URL is returned to the customer's browser and works temporarily.
3. Admins upload paid content (PDFs/videos) directly to the `paid-content` bucket via the admin UI
   using the authenticated Supabase client.
*/

