-- ============================================================
-- public-assets policies
-- ============================================================

DROP POLICY IF EXISTS "public_assets_read" ON storage.objects;
CREATE POLICY "public_assets_read" ON storage.objects
  FOR SELECT TO anon, authenticated
  USING (bucket_id = 'public-assets');

DROP POLICY IF EXISTS "public_assets_insert_admin" ON storage.objects;
CREATE POLICY "public_assets_insert_admin" ON storage.objects
  FOR INSERT TO authenticated
  WITH CHECK (bucket_id = 'public-assets' AND is_admin());

DROP POLICY IF EXISTS "public_assets_update_admin" ON storage.objects;
CREATE POLICY "public_assets_update_admin" ON storage.objects
  FOR UPDATE TO authenticated
  USING (bucket_id = 'public-assets' AND is_admin())
  WITH CHECK (bucket_id = 'public-assets' AND is_admin());

DROP POLICY IF EXISTS "public_assets_delete_admin" ON storage.objects;
CREATE POLICY "public_assets_delete_admin" ON storage.objects
  FOR DELETE TO authenticated
  USING (bucket_id = 'public-assets' AND is_admin());

